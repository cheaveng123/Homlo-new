// Generates lib/router/routes.generated.ts from the files in app/.
// The app keeps its file-based layout (app/job/[id].tsx -> "/job/123");
// this script turns it into a plain list React Navigation can register.
// Run after adding, removing or renaming a screen:  node scripts/gen-routes.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const appDir = path.join(root, "app");
const files = [];
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/\.tsx?$/.test(entry.name) && !entry.name.startsWith("_")) files.push(full);
  }
})(appDir);

// Only files that export a screen component count as routes.
const routes = files
  .filter((f) => /export\s+(default|\{\s*default\s*\})/.test(fs.readFileSync(f, "utf8")))
  .map((f) => {
    const rel = path.relative(appDir, f).replace(/\\/g, "/").replace(/\.tsx?$/, "");
    const inTabs = rel.startsWith("(tabs)/");
    const name = inTabs ? rel.slice("(tabs)/".length) : rel;
    const pattern =
      "/" +
      rel
        .split("/")
        .filter((s) => !/^\(.*\)$/.test(s))
        .filter((s, i, all) => !(s === "index" && i === all.length - 1))
        .join("/");
    return { name, pattern, inTabs, importPath: "@/app/" + rel };
  })
  .sort((a, b) => Number(b.inTabs) - Number(a.inTabs) || a.name.localeCompare(b.name));

const line = (r) =>
  `  { name: ${JSON.stringify(r.name)}, pattern: ${JSON.stringify(r.pattern)}, inTabs: ${r.inTabs}, ` +
  `getComponent: () => require(${JSON.stringify(r.importPath)}).default },`;

const out = `// AUTO-GENERATED by scripts/gen-routes.mjs from the app/ folder. Do not edit.
/* eslint-disable @typescript-eslint/no-require-imports */
import type { ComponentType } from "react";

export type RouteDef = {
  /** Screen name inside its navigator (tab screens drop the "(tabs)/" prefix). */
  name: string;
  /** URL-style path, e.g. "/job/[id]". */
  pattern: string;
  /** True for screens inside the bottom-tab navigator (app/(tabs)). */
  inTabs: boolean;
  getComponent: () => ComponentType<any>;
};

export const ROUTES: RouteDef[] = [
${routes.map(line).join("\n")}
];
`;
fs.writeFileSync(path.join(root, "lib/router/routes.generated.ts"), out);
console.log(`Wrote ${routes.length} routes`);
